import fs from 'node:fs';
import QRCode from 'qrcode';
import sharp from 'sharp';
import jsQR from 'jsqr';
import assert from 'node:assert/strict';
const url=process.argv[2];
if(!url)throw Error('Usage: node scripts/qr.mjs https://ACCOUNT.github.io/REPOSITORY/');
const u=new URL(url);
if(u.protocol!=='https:'||!u.hostname.endsWith('.github.io')||u.hash||u.search)throw Error('A final HTTPS GitHub Pages URL is required');
const response=await fetch(url);
assert(response.ok,'Public website must be reachable before generating QR');
const html=await response.text();
assert(html.includes('<title>一个想记得世界的人</title>'),'Unexpected website');
const svg=await QRCode.toString(url,{type:'svg',errorCorrectionLevel:'M',margin:4,width:1800,color:{dark:'#141618',light:'#ffffff'}});
const inner=svg.replace(/<svg[^>]*>/,'').replace('</svg>','');
const viewBox=svg.match(/viewBox="([^"]+)"/)[1];
const poster=`<svg xmlns="http://www.w3.org/2000/svg" width="2400" height="2800" viewBox="0 0 2400 2800"><rect width="2400" height="2800" fill="white"/><svg x="250" y="150" width="1900" height="1900" viewBox="${viewBox}">${inner}</svg><g text-anchor="middle" fill="#141618" font-family="Microsoft YaHei, Noto Sans CJK SC, sans-serif"><text x="1200" y="2290" font-size="110">一个想记得世界的人</text><text x="1200" y="2470" font-size="64">扫码阅读完整文章</text></g></svg>`;
fs.mkdirSync('qr',{recursive:true});fs.writeFileSync('qr/一个想记得世界的人.svg',poster);
await sharp(Buffer.from(poster),{density:72}).png().toFile('qr/一个想记得世界的人.png');
const {data,info}=await sharp('qr/一个想记得世界的人.png').ensureAlpha().raw().toBuffer({resolveWithObject:true});
const decoded=jsQR(new Uint8ClampedArray(data),info.width,info.height);
assert.equal(decoded?.data,url,'QR decoded URL mismatch');
fs.writeFileSync('reports/qr-check.json',JSON.stringify({url,decoded:decoded.data,pngSize:[info.width,info.height],status:'PASS'},null,2));
console.log('PNG and printable SVG generated; QR decode exactly matches '+url);
