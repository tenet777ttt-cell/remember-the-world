async page => {
 const failures=[];const errors=[];const checks=[];const network=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>network.push(r.url()));
 const check=(ok,label)=>{checks.push({label,pass:!!ok});if(!ok)failures.push(label);};
 await page.goto('http://127.0.0.1:4173/remember-the-world/');
 await page.evaluate(()=>localStorage.clear());await page.reload();
 await page.emulateMedia({reducedMotion:'reduce'});
 for(const width of [320,375,390,768,1440]){
  await page.setViewportSize({width,height:900});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`No horizontal overflow at ${width}px`);
 }
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:'output/playwright/desktop-cover.png'});
 check(await page.locator('[data-source-index]').count()===445,'All 445 source paragraphs in browser');
 check(await page.locator('h2[id^="chapter-"]').count()===10,'All ten chapter headings in browser');
 await page.locator('.sidebar [data-size="1"]').click();
 check(await page.locator('#article').evaluate(e=>getComputedStyle(e).fontSize)==='20px','Increase font size');
 await page.locator('.sidebar [data-size="-1"]').click();
 check(await page.locator('#article').evaluate(e=>getComputedStyle(e).fontSize)==='19px','Decrease font size');
 await page.locator('.toc a[href="#chapter-5"]').click();
 await page.waitForFunction(()=>Math.abs(document.querySelector('#chapter-5').getBoundingClientRect().top-100)<10);
 check(await page.locator('#progress').evaluate(e=>e.value)>20,'Reading progress advances');
 await page.screenshot({path:'output/playwright/desktop-reading.png'});
 await page.waitForFunction(()=>Object.keys(localStorage).some(k=>k.endsWith('position')&&JSON.parse(localStorage[k]).percent>20));
 await page.goto('http://127.0.0.1:4173/remember-the-world/');
 check(await page.locator('#resume').isVisible(),'Reading memory offers resume after fresh visit');
 await page.locator('#continue').click();
 check(await page.evaluate(()=>scrollY>3000),'Resume restores reading position');
 await page.locator('#top').click();
 await page.waitForFunction(()=>scrollY===0);
 check(await page.evaluate(()=>scrollY===0),'Return to top');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'output/playwright/mobile-cover.png'});
 await page.locator('.mobile-menu').click();
 check(await page.locator('#contents').evaluate(d=>d.open),'Mobile table of contents opens');
 await page.locator('#contents [data-size="1"]').click();
 check(await page.locator('#article').evaluate(e=>getComputedStyle(e).fontSize)==='20px','Mobile font controls');
 await page.locator('.dialog-toc a[href="#chapter-10"]').click();
 await page.waitForFunction(()=>Math.abs(document.querySelector('#chapter-10').getBoundingClientRect().top-100)<10);
 check(!(await page.locator('#contents').evaluate(d=>d.open)),'Mobile menu closes after chapter navigation');
 await page.screenshot({path:'output/playwright/mobile-reading.png'});
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile reading no overflow');
 await page.locator('[data-open="#share"]').click();
 check(await page.locator('#share-url').inputValue()==='http://127.0.0.1:4173/remember-the-world/','Share URL excludes chapter fragment');
 await page.locator('#copy').click();
 check(await page.locator('#status').textContent()==='网址已复制','Clipboard copy feedback');
 await page.keyboard.press('Escape');
 await page.reload();
 check(await page.locator('#article').evaluate(e=>getComputedStyle(e).fontSize)==='20px','Font setting persists');
 await page.goto('http://127.0.0.1:4173/remember-the-world/#chapter-3');
 await page.waitForFunction(()=>Math.abs(document.querySelector('#chapter-3').getBoundingClientRect().top-100)<10);
 check(true,'Direct chapter URL and refresh work under repository subpath');
 check(!await page.locator('#resume').isVisible(),'Explicit chapter URL takes priority over saved position');
 check(network.every(u=>u.startsWith('http://127.0.0.1:4173/')),'No third party browser requests');
 check(errors.length===0,'No uncaught JavaScript errors');
 const result={status:failures.length?'FAIL':'PASS',checks,errors,failures,browser:'Microsoft Edge desktop; mobile viewport emulation',limitations:'No physical iPhone, Android or WeChat test; no HTTPS deployment yet'};
 if(failures.length)throw Error(failures.join('; '));
 return result;
}
